"""
Export utilities for MeetNote meeting minutes.
Generates downloadable PDF, TXT, and Markdown files.
"""

import io
from typing import Optional
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.pdfgen import canvas
from models import MeetingMinutes


class MinutesNumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        
        # Header (page > 1)
        if self._pageNumber > 1:
            self.drawString(54, 750, "MeetNote — Official Meeting Minutes")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(54, 744, 558, 744)

        # Footer
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 45, 558, 45)
        self.drawString(54, 32, "Generated by MeetNote AI Meeting Assistant")
        self.drawRightString(558, 32, f"Page {self._pageNumber} of {page_count}")
        self.restoreState()


def generate_minutes_pdf(minutes: MeetingMinutes) -> bytes:
    """Generates an executive-grade PDF document of the meeting minutes."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#0F172A"),
        spaceAfter=4
    )

    date_style = ParagraphStyle(
        'DocDate',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#64748B"),
        spaceAfter=12
    )

    h1_style = ParagraphStyle(
        'CustomH1',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#1E293B"),
        spaceBefore=12,
        spaceAfter=6,
        keepWithNext=True
    )

    body_style = ParagraphStyle(
        'CustomBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9.5,
        leading=14,
        textColor=colors.HexColor("#334155"),
        spaceAfter=6
    )

    box_style = ParagraphStyle(
        'BoxStyle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9.5,
        leading=14,
        textColor=colors.HexColor("#1E293B"),
        backColor=colors.HexColor("#F8FAFC"),
        borderColor=colors.HexColor("#E2E8F0"),
        borderWidth=1,
        borderPadding=10,
        spaceAfter=10
    )

    cell_style = ParagraphStyle(
        'CellText',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#1E293B")
    )

    cell_bold = ParagraphStyle(
        'CellBold',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#0F172A")
    )

    elements = []

    # Title & Date
    elements.append(Paragraph(f"📋 {minutes.meeting_title}", title_style))
    if minutes.meeting_date and minutes.meeting_date != "Not specified":
        elements.append(Paragraph(f"📅 Date: {minutes.meeting_date}", date_style))
    else:
        elements.append(Spacer(1, 4))
    
    elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E2E8F0"), spaceAfter=10, spaceBefore=4))

    # Executive Summary
    elements.append(Paragraph("1. Executive Summary", h1_style))
    elements.append(Paragraph(minutes.meeting_summary, box_style))

    # Key Discussion Points
    if minutes.key_discussion_points:
        elements.append(Paragraph("2. Key Discussion Points", h1_style))
        for pt in minutes.key_discussion_points:
            elements.append(Paragraph(f"• {pt}", body_style))
        elements.append(Spacer(1, 4))

    # Decisions Made
    elements.append(Paragraph("3. Decisions Made", h1_style))
    if minutes.key_decisions:
        for d in minutes.key_decisions:
            elements.append(Paragraph(f"✅ <b>{d}</b>", body_style))
    else:
        elements.append(Paragraph("<i>No explicit decisions recorded.</i>", body_style))
    elements.append(Spacer(1, 4))

    # Action Items Table
    elements.append(Paragraph("4. Action Items & Responsible Persons", h1_style))
    if minutes.action_items:
        table_data = [
            [
                Paragraph("<b>#</b>", cell_bold),
                Paragraph("<b>Action Task</b>", cell_bold),
                Paragraph("<b>Responsible Person</b>", cell_bold),
                Paragraph("<b>Deadline</b>", cell_bold),
                Paragraph("<b>Status</b>", cell_bold)
            ]
        ]
        for idx, item in enumerate(minutes.action_items, 1):
            badge_color = "#166534" if item.verification_status == "SUPPORTED" else ("#92400E" if item.verification_status == "PARTIALLY_SUPPORTED" else "#991B1B")
            status_text = f"<font color='{badge_color}'><b>{item.verification_status}</b></font>"
            table_data.append([
                Paragraph(str(idx), cell_style),
                Paragraph(item.description, cell_style),
                Paragraph(item.owner, cell_style),
                Paragraph(item.deadline, cell_style),
                Paragraph(status_text, cell_style)
            ])

        t_actions = Table(table_data, colWidths=[24, 230, 95, 85, 70])
        t_actions.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#F1F5F9")),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CBD5E1")),
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
            ('TOPPADDING', (0,0), (-1,-1), 4),
            ('BOTTOMPADDING', (0,0), (-1,-1), 4),
        ]))
        elements.append(t_actions)
    else:
        elements.append(Paragraph("<i>No action items identified.</i>", body_style))
    elements.append(Spacer(1, 6))

    # Next Meeting Details
    if minutes.next_meeting_details and minutes.next_meeting_details != "Not specified":
        elements.append(Paragraph("5. Next Meeting Details", h1_style))
        elements.append(Paragraph(f"🗓️ {minutes.next_meeting_details}", body_style))
        elements.append(Spacer(1, 4))

    # Unresolved Questions
    if minutes.unresolved_questions:
        elements.append(Paragraph("6. Unresolved Questions & Follow-ups", h1_style))
        for q in minutes.unresolved_questions:
            elements.append(Paragraph(f"❓ {q}", body_style))

    doc.build(elements, canvasmaker=MinutesNumberedCanvas)
    buffer.seek(0)
    return buffer.getvalue()


def generate_minutes_txt(minutes: MeetingMinutes) -> str:
    """Formats meeting minutes as a clean plain text document."""
    lines = [
        "=" * 60,
        f"MEETING MINUTES: {minutes.meeting_title.upper()}",
        "=" * 60,
        f"Date: {minutes.meeting_date}",
        "",
        "1. EXECUTIVE SUMMARY",
        "-" * 40,
        minutes.meeting_summary,
        ""
    ]

    if minutes.key_discussion_points:
        lines.append("2. KEY DISCUSSION POINTS")
        lines.append("-" * 40)
        for pt in minutes.key_discussion_points:
            lines.append(f"  * {pt}")
        lines.append("")

    lines.append("3. DECISIONS MADE")
    lines.append("-" * 40)
    if minutes.key_decisions:
        for d in minutes.key_decisions:
            lines.append(f"  [x] {d}")
    else:
        lines.append("  (No explicit decisions recorded)")
    lines.append("")

    lines.append("4. ACTION ITEMS & RESPONSIBILITIES")
    lines.append("-" * 40)
    if minutes.action_items:
        for idx, item in enumerate(minutes.action_items, 1):
            lines.append(f"  {idx}. {item.description}")
            lines.append(f"     Owner:    {item.owner}")
            lines.append(f"     Deadline: {item.deadline}")
            lines.append(f"     Evidence: \"{item.evidence}\"")
            lines.append(f"     Audit:    {item.verification_status}")
            lines.append("")
    else:
        lines.append("  (No action items assigned)")
        lines.append("")

    if minutes.next_meeting_details and minutes.next_meeting_details != "Not specified":
        lines.append("5. NEXT MEETING DETAILS")
        lines.append("-" * 40)
        lines.append(f"  {minutes.next_meeting_details}")
        lines.append("")

    if minutes.unresolved_questions:
        lines.append("6. UNRESOLVED QUESTIONS")
        lines.append("-" * 40)
        for q in minutes.unresolved_questions:
            lines.append(f"  ? {q}")
        lines.append("")

    lines.append("=" * 60)
    return "\n".join(lines)


def generate_minutes_markdown(minutes: MeetingMinutes) -> str:
    """Formats meeting minutes as GitHub-flavored Markdown."""
    lines = [
        f"# 📋 {minutes.meeting_title}",
        f"**Date:** {minutes.meeting_date}  ",
        "---",
        "## 1. Executive Summary",
        f"{minutes.meeting_summary}\n"
    ]

    if minutes.key_discussion_points:
        lines.append("## 2. Key Discussion Points")
        for pt in minutes.key_discussion_points:
            lines.append(f"- {pt}")
        lines.append("")

    lines.append("## 3. Decisions Made")
    if minutes.key_decisions:
        for d in minutes.key_decisions:
            lines.append(f"- ✅ **{d}**")
    else:
        lines.append("_No explicit decisions recorded._")
    lines.append("")

    lines.append("## 4. Action Items")
    if minutes.action_items:
        for idx, item in enumerate(minutes.action_items, 1):
            status_emoji = "🟢" if item.verification_status == "SUPPORTED" else ("🟡" if item.verification_status == "PARTIALLY_SUPPORTED" else "🔴")
            lines.append(f"### {idx}. {item.description}")
            lines.append(f"- **Responsible Person:** `{item.owner}`")
            lines.append(f"- **Deadline:** `{item.deadline}`")
            lines.append(f"- **Audit Status:** {status_emoji} `{item.verification_status}`")
            lines.append(f"- **Evidence Quote:** > *\"{item.evidence}\"*")
            lines.append("")
    else:
        lines.append("_No actionable items identified._\n")

    if minutes.next_meeting_details and minutes.next_meeting_details != "Not specified":
        lines.append("## 5. Next Meeting Details")
        lines.append(f"🗓️ **{minutes.next_meeting_details}**\n")

    if minutes.unresolved_questions:
        lines.append("## 6. Unresolved Questions")
        for q in minutes.unresolved_questions:
            lines.append(f"- ❓ {q}")
        lines.append("")

    return "\n".join(lines)
